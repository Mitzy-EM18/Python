def imprimir_lista_de_compras(lista):
    for elemento in lista:
        print("El elemento comprado es:", elemento)
    print("Compra finalizada")

# Lista de compras
lista_de_compras = ["manzanas", "pan", "leche", "huevos", "pasta", "arroz"]

# Llamada a la función para imprimir la lista de compras
imprimir_lista_de_compras(lista_de_compras)
